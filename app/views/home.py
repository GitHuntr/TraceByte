"""Overview page: project scope, evidence status and roadmap."""

from __future__ import annotations

import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

import streamlit as st

from app.branding import DISCLAIMER, PROJECT_REFERENCE, STAGE_LABEL
from app.state import get_integrity_results, get_manifest
from src.experiment_log import ExperimentLog
from src.paths import EXPERIMENT_LOG_PATH, MANIFEST_PATH, ORIGINALS_DIR

st.subheader("Purpose")
st.markdown(
    "FileCarveLab measures how accurately a file-signature carving engine "
    "recovers files that are **contiguous**, **fragmented** or **partially "
    "overwritten**. The experiment is deliberately reproducible: every input is "
    "synthetic, every baseline is hashed with SHA-256, and every action is "
    "written to an append-only experiment log."
)

manifest = get_manifest(str(MANIFEST_PATH))
results, summary = get_integrity_results(str(MANIFEST_PATH), str(ORIGINALS_DIR))
log = ExperimentLog(EXPERIMENT_LOG_PATH)

col_a, col_b, col_c, col_d = st.columns(4)
col_a.metric("Fixtures in baseline", len(manifest.entries))
col_b.metric("Verified intact", summary.get("MATCH", 0))
col_c.metric("Integrity problems", summary.get("MISMATCH", 0) + summary.get("MISSING", 0))
col_d.metric("Logged events", log.event_count())

with st.container(border=True):
    st.markdown("**Forensic guardrails applied in this project**")
    st.markdown(
        "- Only synthetic, locally generated fixtures are used. No real device, "
        "account or third-party data is involved.\n"
        "- Ground-truth originals, experimental inputs and recovered output live in "
        "separate directories and are never mixed.\n"
        "- Baseline SHA-256 hashes are written once and are never regenerated by a "
        "re-run; changes are reported instead.\n"
        "- Signature detection, file recovery and content validation are recorded "
        "as separate, independent observations.\n"
        "- No destructive disk operation is performed anywhere in the pipeline.\n"
        "- Synthetic fixtures that imitate a JPEG, PDF or ZIP signature are labelled "
        "as **not fully parseable** and are never presented as valid recovered files."
    )

with st.container(border=True):
    st.markdown("**Roadmap**")
    st.markdown(
        "| Stage | Scope | Status |\n"
        "| --- | --- | --- |\n"
        "| 1 | Project scaffold, synthetic dataset, SHA-256 manifest, integrity "
        "screen, test suite | Complete |\n"
        "| 2 | Signature scanner and carving engine over the three storage "
        "conditions | Not started |\n"
        "| 3 | Recovery pipeline, content validation and ground-truth matching | "
        "Not started |\n"
        "| 4 | Precision / recall measurement and results dashboard | Not started |\n"
        "| 5 | Failure analysis, limitations and final report | Not started |"
    )

st.caption(f"{PROJECT_REFERENCE} | {STAGE_LABEL}")
st.info(DISCLAIMER)
