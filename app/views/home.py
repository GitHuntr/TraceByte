"""Overview page: project scope, evidence status and roadmap."""

from __future__ import annotations

import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

import streamlit as st

import src.paths as paths
from app.branding import DISCLAIMER
from app.state import get_integrity_results, get_manifest
from app.ui import Kpi, empty_state, kpi_row, notice, page_header, section, status_badge
from src.experiment_log import ExperimentLog

page_header(
    "Overview",
    "FileCarveLab measures how accurately a file-signature carving engine "
    "recovers files that are **contiguous**, **fragmented** or **partially "
    "overwritten**. Every input is synthetic, every baseline is hashed with "
    "SHA-256, and every action is written to an append-only experiment log.",
    icon="dashboard",
)

manifest = get_manifest(str(paths.MANIFEST_PATH))
_results, summary = get_integrity_results(
    str(paths.MANIFEST_PATH), str(paths.ORIGINALS_DIR)
)
log = ExperimentLog(paths.EXPERIMENT_LOG_PATH, enabled=False)

problems = summary.get("MISMATCH", 0) + summary.get("MISSING", 0)

kpi_row(
    [
        Kpi("Fixtures in baseline", len(manifest.entries), help="Ground-truth files recorded in manifest.json"),
        Kpi("Verified intact", summary.get("MATCH", 0), help="Originals whose SHA-256 still matches the baseline"),
        Kpi("Integrity problems", problems, help="Mismatched or missing originals"),
        Kpi("Logged events", log.event_count(), help="Records in the append-only experiment log"),
    ]
)

with section(
    "Pipeline",
    icon="route",
    caption="Four stages, each one reproducible from the artefacts of the previous one.",
):
    with st.container(horizontal=True):
        for icon, name, text in (
            ("folder_open", "Ground truth", "Synthetic originals plus a SHA-256 baseline manifest."),
            ("view_stream", "Controlled images", "One image per storage condition, built from the originals."),
            ("content_cut", "Carving", "Signature scan, byte-range extraction, candidate written to disk."),
            ("query_stats", "Measurement", "Detection, carving and validation measured against ground truth."),
        ):
            with st.container(border=True, width="content"):
                st.markdown(f":material/{icon}: **{name}**")
                st.caption(text)

with section("Evidence status", icon="verified"):
    if not manifest.entries:
        empty_state(
            "folder_open",
            "No evidence set yet",
            "Open **Dataset** and press *Initialise dataset* to create the synthetic "
            "ground truth and its baseline manifest.",
        )
    else:
        with st.container(horizontal=True, vertical_alignment="center"):
            if problems:
                st.markdown("Evidence set")
                status_badge("MISMATCH")
            else:
                st.markdown("Evidence set")
                status_badge("MATCH")
            st.caption(
                f"{summary.get('MATCH', 0)} of {len(manifest.entries)} originals match "
                "their recorded baseline."
            )
        st.caption(
            "A baseline hash is written once and never regenerated. A changed or "
            "missing original is reported, never silently re-baselined."
        )

with section(
    "Forensic guardrails",
    icon="gavel",
    caption="Rules that are enforced by the code, not only by convention.",
):
    for icon, text in (
        ("science", "Only synthetic, locally generated fixtures are used - no real device, account or third-party data."),
        ("folder", "Ground-truth originals, experimental inputs and recovered output live in separate directories."),
        ("lock", "Baseline SHA-256 hashes are written once and are never regenerated by a re-run."),
        ("rule", "Signature detection, file recovery and content validation are recorded as separate observations."),
        ("shield", "No destructive disk operation is performed anywhere in the pipeline."),
        ("label", "Signature-shaped fixtures are labelled **not fully parseable** and never presented as valid files."),
    ):
        st.markdown(f":material/{icon}: {text}")

with section(
    "Roadmap",
    icon="flag",
    caption="Where the project stands in the Digital Forensics PBL.",
):
    for stage, scope, status in (
        ("Stage 1", "Project scaffold, synthetic dataset, SHA-256 manifest, integrity screen, test suite", "COMPLETE"),
        ("Stage 2", "Signature scanner and carving engine over the three storage conditions", "COMPLETE"),
        ("Stage 3", "Recovery pipeline, content validation and ground-truth matching", "COMPLETE"),
        ("Stage 4", "Precision / recall measurement and results dashboard", "COMPLETE"),
        ("Stage 5", "Failure analysis, limitations and final report", "NOT STARTED"),
    ):
        with st.container(horizontal=True, vertical_alignment="center"):
            st.markdown(f"**{stage}**")
            st.caption(scope)
            status_badge(status.title())

notice(DISCLAIMER, kind="info", icon="info")
